export function caseDetail(id: string): CaseDetail | undefined {
  const summary = caseSummaries.find((c) => c.id === id || c.ref === id)
  if (!summary) return undefined
  if (summary.ref === 'INV-0264') {
    return {
      ...summary,
      summary:
        'Multiple public reports of a fire near the Kawo transport interchange in Kaduna North. Open-source footage is circulating widely; at least one clip appears recycled. Official channels confirm a fire and response, cause unknown.',
      authorId: people.amaka.id,
      findings: kadunaFindings,
      evidence: kadunaEvidence,
      indicators: kadunaIndicators,
      claims: kadunaClaims,
      timeline: [...kadunaTimeline].reverse(),
      checklist: [
        { label: 'Sources logged and reliability rated', done: true },
        { label: 'Primary media captured as evidence', done: true },
        { label: 'Geolocation attempted and marked', done: true },
        { label: 'Claims extracted and assessed', done: false },
        { label: 'Statements attached to findings', done: false },
      ],
      etag: '"7"',
    }
  }
  const ev = kadunaEvidence
    .slice(0, Math.max(1, Math.min(summary.evidenceCount, 6)))
    .map((e, i) => ({
      ...e,
      id: `${summary.id}-ev-${i}`,
      ref: `EV-2026-${1700 + Number(summary.ref.slice(-3)) * 3 + i}`,
    }))
  return {
    ...summary,
    summary: `Analyst workspace for ${summary.title.toLowerCase()}. Public reporting and submitted media are being assessed; no conclusion is asserted until findings are approved.`,
    authorId: summary.owner.id,
    findings: kadunaFindings
      .slice(0, summary.state === 'triage' || summary.state === 'open' ? 0 : 2)
      .map((f) => ({ ...f, authorName: summary.owner.name })),
    evidence: ev,
    indicators: kadunaIndicators.slice(0, summary.state === 'triage' ? 0 : 2),
    claims: kadunaClaims.slice(0, 2),
    timeline: [
      {
        id: 'x-3',
        at: summary.updatedAt,
        actor: summary.owner.name,
        kind: 'state',
        text: `Case state is ${summary.state.replace('_', ' ')}`,
      },
      {
        id: 'x-2',
        at: ago(200),
        actor: summary.owner.name,
        kind: 'evidence',
        text: `${ev.length} evidence records registered`,
      },
      {
        id: 'x-1',
        at: ago(260),
        actor: 'Intake',
        kind: 'state',
        text: 'Story group sent to triage',
      },
    ],
    checklist: [
      { label: 'Sources logged and reliability rated', done: summary.state !== 'triage' },
      { label: 'Primary media captured as evidence', done: summary.state !== 'triage' },
      { label: 'Claims extracted and assessed', done: !['triage', 'open'].includes(summary.state) },
      {
        label: 'Statements attached to findings',
        done: !['triage', 'open', 'in_assessment'].includes(summary.state),
      },
    ],
    etag: '"3"',
  }
}

